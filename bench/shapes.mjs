// The inputs the cli bench, its profile and the scaling gate run on: one builder for each shape of
// traffic the `cosyte` command reads. Every message is synthetic. The small ones come from
// @cosyte/synth, which builds each through its format's own builder, so each is spec-clean and none
// is a real patient's; the large ones are those messages grown in code, from an index, the way real
// traffic grows: more results, more entries, more claims, or one large embedded document. No file is
// read.
//
// Two kinds of large input, because they cost a parser different things:
// - dense: many small fields (an ORU with thousands of OBX lines, a Bundle of thousands of entries,
//   an 837 batch of thousands of claims), where a parser pays per field;
// - opaque: one large payload in one field (a base64 PDF in an HL7 OBX, a FHIR Binary, a C-CDA
//   nonXMLBody, CT Pixel Data), where a parser should pay little more than a copy.

