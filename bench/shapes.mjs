/* C-CDA ----------------------------------------------------------------------------------------- */

const ccdTexts = pool((seed) => ccdaRoundTrip(generateCcd({ seed })).content);

/** A synthetic C-CDA R2.1 CCD from @cosyte/synth, about 13 KiB. */
export function ccdDocument(i) {
  return ccdTexts()[i % POOL];
}

/** The entries of a CCD's sections, as text: everything from a section's first entry to its last. */
function sectionEntries(text) {
  const out = [];
  for (let at = text.indexOf("<section"); at !== -1; at = text.indexOf("<section", at + 1)) {
    const end = text.indexOf("</section>", at);
    const first = text.indexOf("<entry", at);
    const last = text.lastIndexOf("</entry>", end);
    if (first !== -1 && first < end && last > first) out.push(text.slice(first, last + 8));
  }
  return out;
}

/**
 * A synthetic CCD of about `bytes` bytes: CCD `i` with the entries of its last section repeated from
 * the synthetic pool, as a record with years of results arrives.
 */
export function ccdDense(i, bytes) {
  const text = ccdDocument(i);
  const lastSection = text.lastIndexOf("</section>");
  const lastEntry = text.lastIndexOf("</entry>", lastSection) + 8;
  const blocks = ccdTexts().flatMap((t) => sectionEntries(t));
  const extra = [];
  let n = text.length;
  for (let k = 0; n < bytes; k++) {
    const block = blocks[(i + k) % blocks.length];
    extra.push(block);
    n += block.length;
  }
  return text.slice(0, lastEntry) + extra.join("") + text.slice(lastEntry);
}

/**
 * A synthetic unstructured C-CDA of about `bytes` bytes: the header of CCD `i` with its structured
 * body replaced by a nonXMLBody carrying a base64 PDF, as a scanned document is exchanged.
 */
export function ccdUnstructured(i, bytes) {
  const text = ccdDocument(i);
  const start = text.indexOf("<component><structuredBody");
  const head = `${text.slice(0, start)}<component><nonXMLBody><text mediaType="application/pdf" representation="B64">`;
  const tail = "</text></nonXMLBody></component>\n</ClinicalDocument>\n";
  return head + base64Payload(payloadBytes(bytes - head.length - tail.length), i) + tail;
}
