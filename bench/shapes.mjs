/** 1024. */
export const KIB = 1024;
/** 1024 * 1024. */
export const MIB = 1024 * 1024;

/** How many synthetic seeds a large input draws its repeated parts from, so it is not one part repeated. */
const POOL = 16;

/** The value of `build(seed)` for each seed in `0..POOL-1`, built once. */
function pool(build) {
  let built;
  return () => (built ??= Array.from({ length: POOL }, (_v, seed) => build(seed)));
}

/**
 * `bytes` generated bytes, base64: a stand-in for an embedded document. A fixed linear congruential
 * sequence, so every run builds the same bytes.
 */
export function base64Payload(bytes, seed) {
  const data = Buffer.alloc(bytes);
  let state = (seed * 2654435761 + 1) >>> 0;
  for (let k = 0; k < bytes; k++) {
    state = (Math.imul(state, 1664525) + 1013904223) >>> 0;
    data[k] = state >>> 24;
  }
  return data.toString("base64");
}

/** How many payload bytes fill about `room` characters of base64, at least 3. */
function payloadBytes(room) {
  return Math.max(3, Math.floor(room / 4) * 3);
}

/* HL7 v2 ---------------------------------------------------------------------------------------- */

/** `build(i)`, kept for the first 256 indexes, so a stream of thousands builds each one once. */
function memo(build) {
  const kept = new Map();
  return (i) => {
    if (i >= 256) return build(i);
    let value = kept.get(i);
    if (value === undefined) {
      value = build(i);
      kept.set(i, value);
    }
    return value;
  };
}

/** A synthetic ADT^A01 from @cosyte/synth, about 280 bytes: the most common message there is. */
export const adtMessage = memo(
  (i) => hl7RoundTrip(generateAdt({ seed: i, trigger: "A01" })).content,
);

const oruSegments = pool((seed) => hl7RoundTrip(generateOru({ seed })).content.split("\r"));

/** The MSH, PID and OBR of synthetic ORU^R01 `i`, each ended by a CR. */
function oruHead(i) {
  const segments = oruSegments()[i % POOL];
  return `${segments.filter((s) => !s.startsWith("OBX") && s !== "").join("\r")}\r`;
}

/** Every OBX line of the pool, with its set ID cut off (`|NM|...`), to be numbered again. */
const obxTails = pool((seed) =>
  oruSegments()
    [seed].filter((s) => s.startsWith("OBX|"))
    .map((s) => s.slice(s.indexOf("|", 4))),
);

/**
 * A synthetic ORU^R01 of about `bytes` bytes: the header of ORU `i`, then numeric results drawn from
 * the synthetic pool and numbered in order, as a long lab report or a cumulative panel arrives.
 */
export function oruMessage(i, bytes) {
  const tails = obxTails().flat();
  const head = oruHead(i);
  const lines = [];
  let n = head.length;
  for (let k = 0; n < bytes; k++) {
    const line = `OBX|${String(k + 1)}${tails[(k + i) % tails.length]}`;
    lines.push(line);
    n += line.length + 1;
  }
  return `${head}${lines.join("\r")}\r`;
}

/**
 * A synthetic ORU^R01 of about `bytes` bytes that carries one document: the header of ORU `i` and
 * one OBX of value type ED whose fifth component is a base64 PDF. This is how a real message usually
 * reaches a MiB: one large field, not many lines.
 */
export function oruDocument(i, bytes) {
  const head = `${oruHead(i)}OBX|1|TX|11502-2^Laboratory report^LN||Report attached||||||F\r`;
  const prefix = "OBX|2|ED|11502-2^Laboratory report^LN||^AP^PDF^Base64^";
  const suffix = "||||||F\r";
  const room = bytes - head.length - prefix.length - suffix.length;
  return head + prefix + base64Payload(payloadBytes(room), i) + suffix;
}

/* MLLP ------------------------------------------------------------------------------------------ */

/**
 * An MLLP stream of `frames` synthetic ADT^A01 messages, each framed by VT and FS CR: what an
 * interface engine's capture of one connection holds. Many small messages in a row.
 */
export function mllpStream(frames) {
  const parts = [];
  for (let k = 0; k < frames; k++) parts.push(`\x0b${adtMessage(k % 256)}\x1c\r`);
  return parts.join("");
}

/* FHIR R4 --------------------------------------------------------------------------------------- */

/** A synthetic US Core Patient from @cosyte/synth, about 800 bytes of JSON. */
export const patientResource = memo(
  (i) => fhirRoundTrip(generatePatient({ seed: i, profile: "us-core" })).content,
);

/**
 * NDJSON of `lines` synthetic Patients, one a line: a bulk data export file, many small resources
 * in a row.
 */
export function patientNdjson(lines) {
  const out = [];
  for (let k = 0; k < lines; k++) out.push(`${patientResource(k % 256)}\n`);
  return out.join("");
}

const bundleParts = pool((seed) => {
  const bundle = JSON.parse(fhirRoundTrip(generateBundle({ seed, type: "collection" })).content);
  return { head: { ...bundle, entry: undefined }, entries: bundle.entry };
});

const UUID = /([0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-)[0-9a-f]{12}/g;

/**
 * A synthetic collection Bundle of about `bytes` bytes: the entries of synthetic Bundles (a patient
 * and its clinical spine, wired by urn:uuid references), repeated with every UUID in a copy made its
 * own, so references still resolve within each copy and no two entries share a fullUrl.
 */
export function bundleResource(i, bytes) {
  const { head } = bundleParts()[i % POOL];
  const entries = [];
  let n = JSON.stringify(head).length;
  for (let copy = 0; n < bytes; copy++) {
    const group = JSON.stringify(bundleParts()[(i + copy) % POOL].entries).replace(
      UUID,
      (_m, lead) => `${lead}${copy.toString(16).padStart(12, "0")}`,
    );
    for (const entry of JSON.parse(group)) {
      entries.push(entry);
      n += JSON.stringify(entry).length + 1;
    }
  }
  return JSON.stringify({ ...head, entry: entries });
}

/**
 * A synthetic FHIR Binary of about `bytes` bytes: a base64 PDF in `data`, as a document server
 * returns one. One large opaque field.
 */
export function binaryResource(i, bytes) {
  const head = `{"resourceType":"Binary","id":"syn-binary-${String(i)}","contentType":"application/pdf","data":"`;
  const tail = '"}';
  return head + base64Payload(payloadBytes(bytes - head.length - tail.length), i) + tail;
}

/* X12 ------------------------------------------------------------------------------------------- */

const claimParts = pool((seed) => {
  const text = x12RoundTrip(generate837P({ seed })).content;
  const segments = text.split("~").filter((s) => s !== "");
  const st = segments.findIndex((s) => s.startsWith("ST*"));
  const se = segments.findIndex((s) => s.startsWith("SE*"));
  return {
    envelope: segments.slice(0, st),
    transaction: segments.slice(st, se + 1),
    trailer: segments.slice(se + 1),
  };
});

/** A synthetic 837P from @cosyte/synth, about 900 bytes: one professional claim. */
export function claimMessage(i) {
  return x12RoundTrip(generate837P({ seed: i })).content;
}

/**
 * A synthetic 837P batch of about `bytes` bytes: one interchange and one functional group holding
 * synthetic claim transactions, each with its own control number, as a clearinghouse submits a day
 * of claims. GE01 counts the transactions.
 */
export function claimBatch(i, bytes) {
  const { envelope, trailer } = claimParts()[i % POOL];
  const sets = [];
  let n = envelope.join("~").length + trailer.join("~").length;
  for (let k = 0; n < bytes; k++) {
    const control = String(k + 1).padStart(4, "0");
    const set = claimParts()[(i + k) % POOL].transaction.map((s) => {
      if (s.startsWith("ST*")) return s.replace(/^ST\*837\*[^*]*/, `ST*837*${control}`);
      if (s.startsWith("SE*")) return s.replace(/\*[^*]*$/, `*${control}`);
      return s;
    });
    sets.push(...set);
    n += set.join("~").length + 1;
  }
  const count = sets.filter((s) => s.startsWith("ST*")).length;
  const ge = trailer.map((s) =>
    s.startsWith("GE*") ? s.replace(/^GE\*\d+/, `GE*${String(count)}`) : s,
  );
  return `${[...envelope, ...sets, ...ge].join("~")}~`;
}

/* ASTM ------------------------------------------------------------------------------------------ */

const astmRecords = pool((seed) =>
  astmRoundTrip(generateAstmResult({ seed }))
    .content.split("\r")
    .filter((r) => r !== ""),
);

/** A synthetic ASTM E1394 result report from @cosyte/synth, about 280 bytes. */
export function astmMessage(i) {
  return `${astmRecords()[i % POOL].join("\r")}\r`;
}

/**
 * A synthetic ASTM E1394 report of about `bytes` bytes: one header, then synthetic patient, order,
 * result and comment groups with the patient records numbered in order, then the terminator: an
 * analyzer's run of many samples sent as one message.
 */
export function astmBatch(i, bytes) {
  const header = astmRecords()[i % POOL][0];
  const body = [];
  let n = header.length + 6;
  for (let k = 0; n < bytes; k++) {
    const records = astmRecords()[(i + k) % POOL].filter(
      (r) => !r.startsWith("H") && !r.startsWith("L"),
    );
    for (const record of records) {
      const line = record.startsWith("P|")
        ? record.replace(/^P\|\d+/, `P|${String(k + 1)}`)
        : record;
      body.push(line);
      n += line.length + 1;
    }
  }
  return `${[header, ...body, "L|1|N"].join("\r")}\r`;
}

